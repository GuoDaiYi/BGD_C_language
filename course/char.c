#include <stdio.h>
int main()
{
    char a,b,c;
    // 定义 3 个字符变量，用来保存 3 个字符。
    // a 保存第 1 个字符，b 保存第 2 个，c 保存第 3 个。

    a = putchar(getchar());
    // 这一行要“从里往外”看：
    // 1. getchar()：从键盘读入 1 个字符。
    // 2. putchar(...)：把刚读到的这个字符输出到屏幕。
    // 3. putchar(...) 还会返回“它刚刚输出的那个字符”。
    // 4. 把这个返回的字符保存到变量 a 中。
    //
    // 如果读到的是 'a'：
    // getchar() 得到 'a'
    // putchar('a') 在屏幕上显示 a
    // 同时返回 'a'
    // 所以 a = 'a'

    b = putchar(getchar());
    // 同上：读第 2 个字符，显示它，并把它的值保存到 b。
    // 如果读到 'b'，屏幕显示 b，b = 'b'

    c = putchar(getchar());
    // 同上：读第 3 个字符，显示它，并把它的值保存到 c。
    // 如果读到 'c'，屏幕显示 c，c = 'c'

    putchar(a);
    // 把变量 a 中保存的字符再输出一次。
    // 如果 a 是 'a'，这里再显示一个 a。

    putchar(b);
    // 把变量 b 中保存的字符再输出一次。

    putchar(c);
    // 把变量 c 中保存的字符再输出一次。

    putchar('\n');
    // 输出一个换行符，让光标到下一行。
    // '\n' 就是“换行”的意思。

    return 0;
    // 程序正常结束。
}